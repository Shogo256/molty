"""The superset claim, checked on the standard library of the running Python.

Every file that is valid Python must compile without errors and come out
unchanged apart from the generated-file header.  It takes a while, so it
only runs when asked:

    NEO_STDLIB=1 python -m unittest discover -s tests -p test_stdlib_superset.py
"""

import io
import os
import sys
import sysconfig
import tokenize
import unittest
from pathlib import Path

from neo.compiler import compile_source


@unittest.skipUnless(os.environ.get("NEO_STDLIB") == "1", "set NEO_STDLIB=1 to compile the standard library")
class StandardLibrary(unittest.TestCase):
    def test_every_file_compiles_to_itself(self):
        root = Path(sysconfig.get_paths()["stdlib"])
        files = sorted(p for p in root.rglob("*.py") if "site-packages" not in p.parts)
        identical, invalid, warnings, problems = 0, 0, 0, []
        for path in files:
            raw = path.read_bytes()
            try:
                source = raw.decode(tokenize.detect_encoding(io.BytesIO(raw).readline)[0])
                compile(source, str(path), "exec", dont_inherit=True)
            except (SyntaxError, UnicodeDecodeError, ValueError):
                invalid += 1  # test data that is broken on purpose
                continue
            name = str(path.relative_to(root))
            try:
                result = compile_source(source, path.name)
            except Exception as exc:
                problems.append(f"{name}: neoc crashed: {exc!r}")
                continue
            if not result.ok:
                problems.append(f"{name}: {result.errors[0].format(path.name)}")
                continue
            lines = result.code.splitlines(keepends=True)
            header = next(i for i, line in enumerate(lines) if line.startswith("# Generated by neoc"))
            if "".join(lines[:header] + lines[header + 1 :]) != source:
                problems.append(f"{name}: output differs from the input")
                continue
            identical += 1
            warnings += len(result.warnings)

        print(
            f"\nPython {sys.version.split()[0]}: {identical}/{len(files) - invalid} files unchanged, "
            f"{invalid} invalid on purpose, {warnings} warnings",
            file=sys.stderr,
        )
        self.assertEqual(problems, [], "\n".join(problems[:20]))


if __name__ == "__main__":
    unittest.main()
