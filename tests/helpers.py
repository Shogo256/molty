"""Shared helpers: compile Molty source in memory and import the result."""

import atexit
import importlib
import itertools
import os
import shutil
import sys
import tempfile
import textwrap
import unittest

from molty.compiler import CompileResult, compile_source
from molty.runtime import shutdown_compute_pool

FILENAME = "test.molty.py"
HEADER = "# Generated by moltyc from test.molty.py; edit the .molty.py source, not this file.\n"

# One directory for every compiled module, on sys.path before any worker
# process starts, so compute workers can import the modules too.
MODULE_DIR = tempfile.mkdtemp(prefix="molty-tests-")
sys.path.insert(0, MODULE_DIR)
atexit.register(shutil.rmtree, MODULE_DIR, ignore_errors=True)
_names = itertools.count()


def compile_molty(source: str, **options) -> CompileResult:
    return compile_source(textwrap.dedent(source), FILENAME, **options)


def describe(result: CompileResult) -> str:
    return "\n".join(d.format(FILENAME) for d in result.diagnostics) or "(no diagnostics)"


def load(source: str, **options):
    """Compile ``source`` and import it as a fresh module."""
    result = compile_molty(source, **options)
    if not result.ok:
        raise AssertionError("does not compile:\n" + describe(result))
    name = f"molty_test_{os.getpid()}_{next(_names)}"
    with open(os.path.join(MODULE_DIR, f"{name}.py"), "w", encoding="utf-8") as f:
        f.write(result.code)
    importlib.invalidate_caches()
    return importlib.import_module(name)


class MoltyTestCase(unittest.TestCase):
    def assertCompiles(self, source: str, **options) -> CompileResult:
        result = compile_molty(source, **options)
        self.assertTrue(result.ok, describe(result))
        return result

    def assertClean(self, source: str, **options) -> CompileResult:
        """Compiles with no errors and no warnings."""
        result = self.assertCompiles(source, **options)
        self.assertEqual(result.diagnostics, [], describe(result))
        return result

    def assertError(self, source: str, code: str) -> CompileResult:
        result = compile_molty(source)
        self.assertFalse(result.ok, f"expected {code}, but it compiled")
        self.assertIn(code, [d.code for d in result.errors], describe(result))
        return result

    def assertWarning(self, source: str, code: str, **options) -> CompileResult:
        result = self.assertCompiles(source, **options)
        self.assertEqual([d.code for d in result.warnings], [code], describe(result))
        return result


class ComputeTestCase(MoltyTestCase):
    def tearDown(self) -> None:
        # Fresh workers per test, so each one sees the modules written since.
        shutdown_compute_pool()
